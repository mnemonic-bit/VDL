#!/usr/bin/env python3
"""Regenerate browser identity data from the Python versions used to run VDL.

Example: python3 scripts/generate-tag-identity.py --python python3.11 \
    --python python3.12 --python python3.13 --python python3.14

Each interpreter contributes its own Unicode tables. Keep the native/test and
container versions together: capability negotiation deliberately refuses an
unknown table version rather than approximating server tag identity.
"""

import argparse
import json
from pathlib import Path
import subprocess


COLLECT = r'''
import json
import unicodedata

folds = {}
controls = []
whitespace = []
for code in range(0x110000):
    character = chr(code)
    folded = character.casefold()
    if folded != character:
        folds[str(code)] = folded
    if unicodedata.category(character).startswith('C'):
        if controls and controls[-1][1] == code - 1:
            controls[-1][1] = code
        else:
            controls.append([code, code])
    if character.isspace():
        whitespace.append(code)
print(json.dumps({
    'version': 'python-casefold-' + unicodedata.unidata_version + '-v1',
    'data': {'folds': folds, 'controls': controls, 'whitespace': whitespace},
}, ensure_ascii=True, separators=(',', ':')))
'''

TEMPLATE = r'''// Generated by scripts/generate-tag-identity.py; do not edit Unicode tables by hand.
(function (root) {
    'use strict';
    const VDL = root.VDL = root.VDL || {};
    const tables = IDENTITY_TABLES;
    let version = 'python-casefold-15.0.0-v1';
    if (!Object.hasOwn(tables, version)) version = Object.keys(tables)[0];
    function supports(candidate) {
        return typeof candidate === 'string' && Object.hasOwn(tables, candidate);
    }
    function useVersion(candidate) {
        if (!supports(candidate)) return false;
        version = candidate;
        return true;
    }
    function forbidden(code, ranges) {
        let lo = 0;
        let hi = ranges.length - 1;
        while (lo <= hi) {
            const mid = (lo + hi) >>> 1;
            const range = ranges[mid];
            if (code < range[0]) hi = mid - 1;
            else if (code > range[1]) lo = mid + 1;
            else return true;
        }
        return false;
    }
    function normalize(value) {
        if (typeof value !== 'string') throw new Error('Tag must be text');
        const { folds, controls, whitespace } = tables[version];
        let display = '';
        let gap = false;
        for (const character of value) {
            const code = character.codePointAt(0);
            if (forbidden(code, controls)) throw new Error('Tag must not contain control characters');
            if (whitespace.includes(code)) {
                gap = !!display;
            } else {
                if (gap) display += ' ';
                display += character;
                gap = false;
            }
        }
        if (!display) throw new Error('Tag must not be empty');
        if (display.includes(',')) throw new Error('Tag must not contain commas');
        if (Array.from(display).length > 64) throw new Error('Tag must be 64 characters or fewer');
        const key = Array.from(display, character => folds[character.codePointAt(0)] || character).join('');
        return Object.freeze({ name: display, key });
    }
    VDL.tagIdentity = Object.freeze({
        get version() { return version; },
        supports, useVersion, normalize,
    });
})(typeof window === 'undefined' ? globalThis : window);
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--python', action='append', required=True, dest='interpreters')
    parser.add_argument('--output', type=Path,
                        default=Path(__file__).resolve().parents[1] / 'static/tag-identity.js')
    parser.add_argument('--check', action='store_true', help='verify the checked-in asset without writing')
    args = parser.parse_args()
    tables = {}
    for interpreter in args.interpreters:
        result = subprocess.run([interpreter, '-c', COLLECT], check=True,
                                capture_output=True, text=True)
        data = json.loads(result.stdout)
        tables[data['version']] = data['data']
    source = TEMPLATE.replace('IDENTITY_TABLES', json.dumps(
        dict(sorted(tables.items())), ensure_ascii=True, separators=(',', ':'),
    ))
    if args.check:
        if args.output.read_text(encoding='utf-8') != source:
            raise SystemExit('Tag identity asset differs; regenerate with the same interpreter versions.')
    else:
        args.output.write_text(source, encoding='utf-8')


if __name__ == '__main__':
    main()
